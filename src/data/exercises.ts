export function getExercisesFor(
  language: Exercise['language'],
  level: Exercise['level'],
  skill?: Exercise['skill'],
): Exercise[] {
  return exercises.filter(
    (e) =>
      e.language === language &&
      e.level === level &&
      (skill ? e.skill === skill : true),
  )
}
